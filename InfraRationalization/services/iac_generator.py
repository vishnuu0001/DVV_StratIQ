# ─── Azure ARM Template ───────────────────────────────────────────────────────

# Function: generate_arm_template
def generate_arm_template(report: dict, server_names: Optional[list[str]] = None) -> dict:
    servers = _select_servers(report, server_names)
    resources: list[dict] = []
    for s in servers:
        name = _sanitize_name(s.get("server_name") or s.get("name") or "server")
        cpu = int(s.get("cpu_cores") or 2)
        ram = float(s.get("ram_gb") or s.get("memory_gb") or 4)
        size = _closest_size("azure", cpu, ram)
        resources.append({
            "type": "Microsoft.Compute/virtualMachines",
            "apiVersion": "2023-09-01",
            "name": name,
            "location": "[parameters('location')]",
            "comments": (
                f"Source server: {s.get('server_name', 'unknown')} | "
                f"discovered {cpu} vCPU / {ram} GiB RAM | OS: {s.get('os_name', 'unknown')} | "
                f"size '{size}' is the nearest catalog match — verify against this scan's TCO right-sizing analysis"
            ),
            "properties": {
                "hardwareProfile": {"vmSize": size},
                "osProfile": {
                    "computerName": name,
                    "adminUsername": "REPLACE-ME-admin",
                },
                "storageProfile": {
                    "imageReference": {
                        "publisher": "REPLACE-ME", "offer": "REPLACE-ME", "sku": "REPLACE-ME", "version": "latest",
                    },
                },
                "networkProfile": {
                    "networkInterfaces": [{"id": "[parameters('networkInterfaceId_" + name + "')]"}],
                },
            },
        })

    return {
        "$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#",
        "contentVersion": "1.0.0.0",
        "metadata": {
            "generatedBy": "StratIQ InfraRationalization",
            "sourceScan": report.get("report_name") or report.get("scan_id"),
            "note": (
                "STARTER TEMPLATE — resource group, network interfaces, and image references "
                "are left as parameters/placeholders. Fill these in for your target environment "
                "before deploying; this file is not ready to deploy as-is."
            ),
        },
        "parameters": {
            "location": {"type": "string", "defaultValue": "eastus"},
            **{
                f"networkInterfaceId_{_sanitize_name(s.get('server_name') or s.get('name') or 'server')}": {
                    "type": "string", "defaultValue": "REPLACE-ME-nic-resource-id",
                }
                for s in servers
            },
        },
        "resources": resources,
    }


# ─── AWS CloudFormation ────────────────────────────────────────────────────────

# Function: generate_cloudformation
def generate_cloudformation(report: dict, server_names: Optional[list[str]] = None) -> dict:
    servers = _select_servers(report, server_names)
    resources: dict[str, Any] = {}
    for s in servers:
        name = _sanitize_name(s.get("server_name") or s.get("name") or "server")
        logical_id = "".join(part.capitalize() for part in name.split("-")) or "Server"
        cpu = int(s.get("cpu_cores") or 2)
        ram = float(s.get("ram_gb") or s.get("memory_gb") or 4)
        size = _closest_size("aws", cpu, ram)
        resources[logical_id] = {
            "Type": "AWS::EC2::Instance",
            "Metadata": {
                "SourceServer": s.get("server_name", "unknown"),
                "DiscoveredSpec": f"{cpu} vCPU / {ram} GiB RAM",
                "SourceOS": s.get("os_name", "unknown"),
                "Note": f"'{size}' is the nearest catalog match — verify against this scan's TCO right-sizing analysis",
            },
            "Properties": {
                "InstanceType": size,
                "ImageId": "REPLACE-ME-ami-id",
                "SubnetId": {"Ref": "TargetSubnetId"},
                "SecurityGroupIds": [{"Ref": "TargetSecurityGroupId"}],
                "Tags": [
                    {"Key": "Name", "Value": name},
                    {"Key": "SourceServer", "Value": s.get("server_name", "unknown")},
                    {"Key": "MigrationStrategy", "Value": s.get("migration_strategy", "unspecified")},
                ],
            },
        }

    return {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": (
            f"StratIQ InfraRationalization — starter CloudFormation template from scan "
            f"'{report.get('report_name') or report.get('scan_id')}'. STARTER TEMPLATE, not "
            f"ready to deploy as-is — fill in the placeholder parameters below for your target environment."
        ),
        "Parameters": {
            "TargetSubnetId": {"Type": "AWS::EC2::Subnet::Id", "Description": "REPLACE with your actual target subnet"},
            "TargetSecurityGroupId": {"Type": "AWS::EC2::SecurityGroup::Id", "Description": "REPLACE with your actual target security group"},
        },
        "Resources": resources,
    }


# ─── Unified entry point ──────────────────────────────────────────────────────

# Function: generate_iac
def generate_iac(report: dict, provider: str, iac_format: str, server_names: Optional[list[str]] = None) -> tuple[str, str]:
    """
    Returns (content, content_type). iac_format: 'terraform' | 'arm' | 'cloudformation'.
    """
    provider = provider.lower()
    iac_format = iac_format.lower()

    if iac_format == "terraform":
        return generate_terraform(report, provider, server_names), "text/plain"
    if iac_format == "arm":
        if provider != "azure":
            raise ValueError("ARM templates are Azure-specific; use 'terraform' for other providers")
        return json.dumps(generate_arm_template(report, server_names), indent=2), "application/json"
    if iac_format == "cloudformation":
        if provider != "aws":
            raise ValueError("CloudFormation templates are AWS-specific; use 'terraform' for other providers")
        return json.dumps(generate_cloudformation(report, server_names), indent=2), "application/json"

    raise ValueError(f"Unsupported iac_format: {iac_format}")
